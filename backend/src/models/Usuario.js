class Usuario {
    constructor(id, nombre, email, contraseña, fechaNacimiento, telefono, rol) {
        this.id = id;
        this.nombre = nombre;
        this.email = email;
        this.contraseña = contraseña;
        this.fechaNacimiento = fechaNacimiento;
        this.telefono = telefono;
        this.rol = rol;
    }
}

export default Usuario;
