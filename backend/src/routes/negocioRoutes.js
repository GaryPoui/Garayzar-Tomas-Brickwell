import { Router } from 'express'
import C from '../controllers/NegocioController.js'
import { requireAuth, requireStaff, requireAdmin } from '../middlewares/auth.js'
const router = Router()
router.get('/carta', C.carta)
router.get('/configuracion', C.configuracion)
router.get('/eventos', C.eventos)
router.get('/eventos/:id', C.evento)
router.post('/eventos/:id/entradas', requireAuth, C.comprar)
router.use(requireAuth)
router.get('/entradas', C.entradas)
router.put('/entradas/:id', C.entrada)
router.get('/historial', C.historial)
router.put('/perfil', C.perfil)
router.get('/avisos', C.avisos)
router.put('/avisos/:id', C.leerAviso)
router.get('/clientes', requireStaff, C.clientes)
router.get('/clientes/:id/historial', requireAdmin, C.historialCliente)
router.get('/gestion/catalogo/:tipo', requireStaff, C.catalogo)
router.post('/gestion/catalogo/:tipo', requireAdmin, C.crearCatalogo)
router.put('/gestion/catalogo/:tipo/:id', requireStaff, C.editarCatalogo)
router.delete('/gestion/catalogo/:tipo/:id', requireAdmin, C.eliminarCatalogo)
router.use('/gestion', requireAdmin)
router.get('/gestion/eventos', C.gestionEventos)
router.post('/gestion/eventos', C.crearEvento)
router.put('/gestion/eventos/:id', C.editarEvento)
router.delete('/gestion/eventos/:id', C.eliminarEvento)
router.get('/gestion/usuarios', C.usuarios)
router.post('/gestion/usuarios', C.crearUsuario)
router.put('/gestion/usuarios/:id', C.modificarUsuario)
router.get('/gestion/reportes', C.reportes)
router.put('/gestion/configuracion', C.guardarConfiguracion)
export default router
